#!/usr/bin/env python3
"""Write a day's chapter code out as plain R and Python scripts.

    python3 scripts/make_code.py --day 1        # or: make code DAY=1

The booklet's code lives in the chapters, as live cells that run in the reader's
browser. Those cannot be run in a local R or Python session, which makes the code
awkward to develop and impossible to check before students meet it. This writes
the same code out as ordinary scripts:

    code/day1-code.R
    code/day1-code.py

Open either in Positron and run it line by line like any script. The worked
examples appear in order, and wherever a task cell has blanks for the student to
fill in, the published solution appears instead — so the script is the state a
student reaches by the end of the page.

The chapters are the source. Edit a chapter and re-run this; never edit the
generated script, because the next run overwrites it.
"""

import argparse
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
CELL = re.compile(r"^```\{(webr|pyodide)\}\n((?:#\|[^\n]*\n)*)(.*?)\n```\s*$", re.S | re.M)
LANG = {"webr": ("R", "R", "#"), "pyodide": ("Python", "py", "#")}


def packages(engine: str) -> list[str]:
    cfg = (ROOT / "_quarto.yml").read_text()
    key = "webr" if engine == "webr" else "pyodide"
    m = re.search(rf"^{key}:\n(?:  .*\n)*?  packages:\s*\[(.*?)\]", cfg, re.M)
    return [p.strip() for p in m.group(1).split(",")] if m else []


def heading(text: str) -> str:
    m = re.search(r"^#\s+(.*?)\s*(?:\{#[\w-]+\})?\s*$", text, re.M)
    return m.group(1) if m else "untitled"


def build(day: int, engine: str) -> str:
    name, _, c = LANG[engine]
    chapters = sorted(ROOT.glob(f"day{day}-*.qmd"))
    out = [
        f"{c} {'-' * 70}",
        f"{c} Day {day} — {name} code, extracted from the chapters.",
        f"{c}",
        f"{c} GENERATED by scripts/make_code.py — do not edit this file. Edit the",
        f"{c} chapter it came from and re-run `make code DAY={day}`.",
        f"{c}",
        f"{c} Run it with the project root as the working directory (open",
        f"{c} HDS_M3.Rproj, or setwd() to the project root), because the file paths",
        f"{c} below are relative to it. Where a task has blanks in the booklet, the",
        f"{c} published solution is used here.",
        f"{c} {'-' * 70}",
        "",
    ]
    if engine == "webr":
        out += ["suppressPackageStartupMessages({"] + \
               [f"  library({p})" for p in packages(engine)] + ["})", ""]

    for chapter in chapters:
        text = chapter.read_text()
        cells = []
        for m in CELL.finditer(text):
            eng, opts, body = m.group(1), m.group(2), m.group(3)
            kind = ("solution" if "solution: true" in opts
                    else "hint" if "hint: true" in opts else "main")
            key = re.search(r"exercise:\s*(\S+)", opts)
            cells.append((eng, kind, key.group(1) if key else None, body))
        if not any(e == engine and k == "main" for e, k, _, _ in cells):
            continue
        solutions = {k: b for e, k_, k, b in cells if e == engine and k_ == "solution"}

        out += [f"{c} {'=' * 70}", f"{c} {heading(text)}", f"{c}   {chapter.name}",
                f"{c} {'=' * 70}", ""]
        for e, kind, key, body in cells:
            if e != engine or kind != "main":
                continue
            if "______" in body and key in solutions:
                out += [f"{c} [solution to the `{key}` task]"]
                body = solutions[key]
            elif "______" in body:
                out += [f"{c} [this task has no published solution — blanks left in]"]
            out += [body.rstrip(), ""]
    return "\n".join(out) + "\n"


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--day", type=int, default=1)
    args = ap.parse_args()
    if not sorted(ROOT.glob(f"day{args.day}-*.qmd")):
        print(f"no chapters for day {args.day}", file=sys.stderr)
        return 1
    (ROOT / "code").mkdir(exist_ok=True)
    for engine, (_, ext, _) in LANG.items():
        dest = ROOT / "code" / f"day{args.day}-code.{ext}"
        dest.write_text(build(args.day, engine))
        print(f"wrote {dest.relative_to(ROOT)}  ({len(dest.read_text().splitlines())} lines)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
